#!/usr/bin/env python3
"""Refresh the resolved dependency inventory and preserve upstream legal notices."""

import argparse
import hashlib
import re
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path
from zipfile import ZipFile


ROOT = Path(__file__).resolve().parents[1]
LEGAL_FILE = re.compile(
    r"(?:license|notice|copying|copyright|third[-_]party)(?:[._-][\w.-]+)?", re.I
)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if checked-in notices are stale")
    args = parser.parse_args()
    subprocess.run(
        [
            "mvn", "-B", "license:add-third-party", "dependency:list",
            "-Dlicense.force=true",
            "-DoutputFile=target/license-dependency-list.txt",
            "-DoutputAbsoluteArtifactFilename=true", "-DincludeScope=test",
        ], cwd=ROOT, check=True,
    )
    licenses = {}
    for line in (ROOT / "target/license-audit/THIRD-PARTY.txt").read_text().splitlines():
        coordinate = re.search(r"\(([^\s()]+:[^\s()]+:[^\s()]+) - ", line)
        if not coordinate:
            continue
        # License names may themselves contain parentheses; multiple licenses are
        # printed as adjacent parenthesized groups before the project name.
        remainder = line.strip()
        names = []
        while remainder.startswith("("):
            depth = 0
            for index, char in enumerate(remainder):
                depth += (char == "(") - (char == ")")
                if depth == 0:
                    names.append(remainder[1:index])
                    remainder = remainder[index + 1:].lstrip()
                    break
            else:
                raise RuntimeError(f"Malformed license report line: {line}")
        licenses[coordinate[1]] = "; ".join(names)

    artifacts = []
    notices = {}
    for line in (ROOT / "target/license-dependency-list.txt").read_text().splitlines():
        if ":/" not in line:
            continue
        coordinate, filename = line.strip().split(":/", 1)
        fields = coordinate.split(":")
        group, artifact, kind = fields[:3]
        version, scope = fields[-2:]
        classifier = ":".join(fields[3:-2])
        gav = f"{group}:{artifact}:{version}"
        label = f"{group}:{artifact}:{kind}:" + (f"{classifier}:" if classifier else "") + version
        license_name = licenses.get(gav)
        if not license_name or "Unknown license" in license_name:
            raise RuntimeError(f"No verified license declaration for {gav}")
        path = Path("/" + filename.split(" -- ", 1)[0].strip())
        notice_ids = []
        with ZipFile(path) as archive:
            for entry in sorted(archive.namelist()):
                name = entry.rsplit("/", 1)[-1]
                if not LEGAL_FILE.fullmatch(name) or name.endswith((".class", ".json", ".java")):
                    continue
                data = archive.read(entry)
                if not data.strip():
                    continue
                digest = hashlib.sha256(data).hexdigest()
                record = notices.setdefault(digest, {"data": data, "origins": []})
                record["origins"].append(f"{label} — {entry}")
                notice_ids.append(digest)
        artifacts.append((label, scope, license_name, sorted(set(notice_ids))))

    inventory = [
        "# Resolved third-party dependencies", "",
        "Generated by `python3 tools/update-third-party-licenses.py` from Maven's resolved",
        "dependency graph and inherited POM licenses. Includes compile, runtime, provided,",
        "and test dependencies; build plugins are outside this inventory.", "",
        "`provided` dependencies are supplied by the execution environment; `test` dependencies",
        "are used for testing. Compile/runtime dependencies are candidates for the executable",
        "assembly. Shaded components retain the enclosing artifact's upstream notices below.", "",
        f"Resolved artifacts (including classifiers): **{len(artifacts)}**.", "",
        "The `Notice IDs` refer to SHA-256 sections in `THIRD-PARTY-NOTICES.txt`.",
        "A dash means the JAR does not contain a matching standalone legal file; it does not",
        "mean that no license applies. See `README.md` for supplemental terms and source links.", "",
        "| Maven artifact | Scope | Declared license(s) | Notice IDs |",
        "| --- | --- | --- | --- |",
    ]
    for label, scope, license_name, ids in sorted(artifacts):
        escaped_license = license_name.replace("|", "\\|")
        inventory.append(f"| `{label}` | {scope} | {escaped_license} | {', '.join(ids) or '—'} |")

    # Deduplicate identical texts, retaining all original artifact/path attributions.
    legal = [
        "THIRD-PARTY LICENSES, COPYRIGHTS, AND NOTICES", "",
        "Generated from legal files in the resolved dependency JARs.",
        "Each section retains the upstream bytes (decoded as UTF-8 with a Latin-1 fallback).",
        "Repeated identical files share a section with all their original locations listed.",
        "These include notices for components shaded inside dependency artifacts.", "",
    ]
    for digest, record in sorted(notices.items()):
        legal += ["=" * 78, "SHA-256: " + digest, "Original locations:"]
        legal += ["  " + origin for origin in sorted(record["origins"])]
        legal += ["-" * 78]
        try:
            text = record["data"].decode("utf-8")
        except UnicodeDecodeError:
            text = record["data"].decode("latin-1")
        legal += [text, ""]

    outputs = {
        ROOT / "license/THIRD-PARTY.md": "\n".join(inventory) + "\n",
        ROOT / "license/THIRD-PARTY-NOTICES.txt": "\n".join(legal) + "\n",
    }
    pom = ET.parse(ROOT / "pom.xml").getroot()
    ns = {"m": "http://maven.apache.org/POM/4.0.0"}
    direct = []
    for dependency in pom.findall("m:dependencies/m:dependency", ns):
        group = dependency.findtext("m:groupId", namespaces=ns)
        artifact = dependency.findtext("m:artifactId", namespaces=ns)
        prefix = f"{group}:{artifact}:"
        matches = [row for row in artifacts if row[0].startswith(prefix)]
        if len(matches) != 1:
            raise RuntimeError(f"Cannot identify the direct dependency {group}:{artifact}")
        label, scope, license_name, _ = matches[0]
        direct += [f"{label} [{scope}]", f"  {license_name}", ""]
    license_path = ROOT / "LICENSE.txt"
    current = license_path.read_text()
    begin = "BEGIN GENERATED DIRECT DEPENDENCIES\n"
    end = "END GENERATED DIRECT DEPENDENCIES"
    before, remainder = current.split(begin, 1)
    _, after = remainder.split(end, 1)
    outputs[license_path] = before + begin + "\n".join(direct) + end + after
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode("utf-8"):
                raise RuntimeError(f"Stale license inventory: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)
    print(f"Verified {len(artifacts)} artifacts and {len(notices)} distinct upstream legal files.")


if __name__ == "__main__":
    main()
